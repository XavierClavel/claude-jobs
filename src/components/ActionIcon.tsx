// The mark of what an action sends with. Decorative: the action's name says the rest.
export function ActionIcon({
  action,
  size = 14,
}: {
  action: Pick<Action, 'target'>
  size?: number
}) {
  if (action.target.kind !== 'slack') return null
  return (
    <svg
      className="action-icon"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      aria-hidden="true"
      data-kind="slack"
    >
      {SLACK.map(([fill, d]) => (
        <path key={fill} fill={fill} d={d} />
      ))}
    </svg>
  )
}
